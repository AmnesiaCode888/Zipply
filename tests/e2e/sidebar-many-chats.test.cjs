const { test } = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const { chromium } = require('playwright-core')
const { buildSync } = require('esbuild')

const browserPath = [process.env.CHROME_PATH, 'C:/Program Files/Google/Chrome/Application/chrome.exe', 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe', '/usr/bin/google-chrome', '/usr/bin/chromium'].find(value => value && fs.existsSync(value))

test('large chat lists render a bounded number of rows and remain navigable', { timeout: 30000, skip: !browserPath && 'Chromium executable is unavailable' }, async () => {
  const assets = path.join('out', 'renderer', 'assets')
  const cssName = fs.readdirSync(assets).find(name => name.startsWith('index-') && name.endsWith('.css'))
  assert.ok(cssName, 'build the renderer before running UI tests')
  const script = buildSync({ stdin: { contents: `import React from 'react'; import {createRoot} from 'react-dom/client'; import {Sidebar} from './src/renderer/src/components/sidebar/Sidebar';
const sessions = Array.from({length: 1000}, (_, i) => ({id: String(i), title: 'Chat ' + i, createdAt: 1, updatedAt: 1000-i, folderPath: 'C:/project', messages: []}));
createRoot(document.getElementById('root')).render(<Sidebar sessions={sessions} activeChatId="0" onSelectChat={id => {window.selectedChat=id}} onRenameChat={(id,title) => {window.renamedChat=[id,title]}} onDeleteChat={id => {window.deletedChat=id}} />);`, resolveDir: process.cwd(), loader: 'tsx' }, bundle: true, write: false, format: 'iife', jsx: 'automatic', loader: { '.svg': 'dataurl' }, platform: 'browser' }).outputFiles[0].text
  const browser = await chromium.launch({ headless: true, executablePath: browserPath })
  try {
    const page = await browser.newPage({ viewport: { width: 300, height: 700 } })
    await page.setContent('<style>html,body,#root {height:100%;margin:0}</style><div id="root"></div>')
    await page.addStyleTag({ content: fs.readFileSync(path.join(assets, cssName), 'utf8') })
    await page.evaluate(() => { window.api = { storage: { get: key => ({ exists: true, value: key === 'zipply_projects_v1' ? JSON.stringify(['C:/project']) : null }) } } })
    await page.addScriptTag({ content: script })
    const rows = page.locator('[role="button"][tabindex="0"]')
    await page.getByRole('button', { name: 'Chat 0', exact: true }).waitFor()
    assert.ok(await rows.count() < 80, 'only rows near the viewport are mounted')
    await page.getByRole('button', { name: 'project', exact: true }).click()
    await page.waitForTimeout(300)
    assert.ok(await rows.count() < 120, 'the expanded project also uses a bounded number of rows')
    const scroll = page.locator('[data-chat-scroll]')
    const projectList = page.locator('[role="list"]').first()
    const editing = projectList.getByRole('button', { name: 'Chat 0', exact: true })
    await editing.dblclick()
    const input = projectList.locator('input')
    await input.fill('Renamed chat')
    const editBox = await input.boundingBox()
    const nextBox = await projectList.getByRole('button', { name: 'Chat 1', exact: true }).boundingBox()
    assert.ok(editBox.y + editBox.height <= nextBox.y, 'editing does not overlap the next row')
    await scroll.evaluate(element => { element.scrollTop = element.scrollHeight })
    await page.waitForTimeout(500)
    assert.equal(await input.inputValue(), 'Renamed chat', 'the focused editor stays mounted while scrolling')
    await input.press('Enter')
    assert.deepEqual(await page.evaluate(() => window.renamedChat), ['0', 'Renamed chat'])
    await page.getByRole('button', { name: 'Chat 999', exact: true }).last().waitFor({ timeout: 5000 })
    await page.getByRole('button', { name: 'Chat 999', exact: true }).last().click()
    assert.equal(await page.evaluate(() => window.selectedChat), '999')
    assert.ok(await rows.count() < 120, 'scrolling to the end stays bounded')
    const previous = page.getByRole('button', { name: 'Предыдущие чаты' }).last()
    const previousIndex = await previous.evaluate(button => Number(button.parentElement.querySelector('[data-virtual-row]').getAttribute('data-virtual-row')) - 1)
    await previous.focus()
    await page.waitForFunction(index => document.activeElement?.getAttribute('aria-label') === `Chat ${index}`, previousIndex, { timeout: 3000 })
    await scroll.evaluate(element => { element.scrollTop = 0 })
    await page.getByRole('button', { name: 'project', exact: true }).click()
    await page.waitForTimeout(300)
    assert.equal(await page.locator('[role="list"]').count(), 1, 'closed projects unmount their rows')
    const recent = page.locator('[role="list"]').last()
    await scroll.evaluate(element => { element.scrollTop = 0 })
    await page.waitForTimeout(200)
    const lastRow = recent.locator('[data-virtual-row]').last()
    const lastIndex = Number(await lastRow.getAttribute('data-virtual-row'))
    await lastRow.locator('[role="button"]').evaluate(element => element.focus({ preventScroll: true }))
    await lastRow.getByTitle('Удалить').evaluate(element => element.focus({ preventScroll: true }))
    await page.keyboard.press('Tab')
    await page.waitForFunction(index => document.activeElement?.getAttribute('aria-label') === `Chat ${index}`, lastIndex + 1, { timeout: 3000 })
    const firstRow = recent.locator('[data-virtual-row]').first()
    const firstIndex = Number(await firstRow.getAttribute('data-virtual-row'))
    await firstRow.locator('[role="button"]').evaluate(element => element.focus({ preventScroll: true }))
    await page.keyboard.press('Shift+Tab')
    await page.waitForFunction(index => document.activeElement?.getAttribute('aria-label') === `Chat ${index}`, firstIndex - 1, { timeout: 3000 })
    await page.getByRole('button', { name: 'Открыть поиск по чатам' }).click()
    await page.getByRole('searchbox', { name: 'Поиск по чатам и сообщениям' }).fill('Chat 999')
    await page.getByRole('button', { name: /Chat 999/ }).click()
  } finally { await browser.close() }
})
