const { test } = require('node:test')
const assert = require('node:assert/strict')
const fs = require('node:fs')
const path = require('node:path')
const { chromium } = require('playwright-core')
const { buildSync } = require('esbuild')

const browserPath = [process.env.CHROME_PATH, 'C:/Program Files/Google/Chrome/Application/chrome.exe', 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe', '/usr/bin/google-chrome', '/usr/bin/chromium'].find(value => value && fs.existsSync(value))

test('large chat mounts a bounded window and keeps legacy reasoning hidden after navigation', { timeout: 30000, skip: !browserPath && 'Chromium is unavailable' }, async () => {
  const assets = path.join('out', 'renderer', 'assets')
  const cssName = fs.readdirSync(assets).find(name => name.startsWith('index-') && name.endsWith('.css'))
  const css = fs.readFileSync(path.join(assets, cssName), 'utf8')
  const script = buildSync({ stdin: { contents: `import React from 'react'; import { createRoot } from 'react-dom/client'; import { MessageFeed } from './src/renderer/src/components/chat/MessageFeed';
let messages = Array.from({length: 500}, (_, i) => ({ id: 'm'+i, role: 'assistant', blocks: i === 150 ? [{type:'thinking',id:'thought',content:'remember this thought',durationSec:1},{type:'text',id:'visible-150',content:'Visible message 150'}] : i === 200 ? [{type:'tool', id:'tool-200', tool:{id:'tool-200',type:'file_read',toolName:'read_file',label:'Прочитал',status:'completed',content:'result'}}] : [{type:'text',id:'b'+i,content:'Message '+i+' '.repeat(i%7)}] }));
let target = null; const root = createRoot(document.getElementById('root')); const render = () => root.render(<MessageFeed messages={messages} searchTarget={target}/>); window.go = (index, sequence) => { target = index == null ? null : {messageId:'m'+index,sequence}; render() }; window.extend = () => { const last=messages.at(-1); messages=[...messages.slice(0,-1), {...last, blocks:[{...last.blocks[0], content:last.blocks[0].content+'\\nnew line'.repeat(40)}]}]; render() }; window.searchWhileSending = () => { messages=[...messages,{id:'new-user',role:'user',content:'question'},{id:'new-assistant',role:'assistant',blocks:[{type:'text',id:'new-block',content:'start'}]}];target={messageId:'m50',sequence:42};render() }; window.go(null,0);`, resolveDir: process.cwd(), loader: 'tsx' }, bundle: true, write: false, format: 'iife', loader: { '.svg': 'dataurl' }, platform: 'browser' }).outputFiles[0].text
  const browser = await chromium.launch({ headless: true, executablePath: browserPath })
  try {
    const page = await browser.newPage({ viewport: { width: 800, height: 600 } })
    await page.setContent('<div id="root" style="display:flex;height:600px"></div>')
    await page.addStyleTag({ content: css })
    await page.addScriptTag({ content: script })
    await page.locator('[data-message-id]').first().waitFor({ timeout: 3000 })
    await page.waitForTimeout(250)
    assert.ok(await page.locator('[data-message-id]').count() < 100)
    await page.evaluate(() => window.go(150, 1))
    const row = page.locator('[data-message-id="m150"]')
    await row.waitFor()
    assert.equal(await row.getByText('remember this thought').count(), 0)
    await row.getByText('Visible message 150').waitFor()
    await page.evaluate(() => window.go(499, 2))
    await page.locator('[data-message-id="m499"]').waitFor()
    await page.evaluate(() => window.go(150, 3))
    await row.waitFor()
    assert.equal(await row.getByText('remember this thought').count(), 0)
    await row.getByText('Visible message 150').waitFor()
    await page.evaluate(() => window.go(200, 31))
    const group = page.locator('[data-message-id="m200"]')
    await group.waitFor()
    await group.getByRole('button', { name: 'Чтение файлов' }).click()
    await page.evaluate(() => window.go(499, 32))
    await page.locator('[data-message-id="m499"]').waitFor()
    await page.evaluate(() => window.go(200, 33))
    await group.waitFor()
    assert.equal(await group.getByRole('button', { name: 'Чтение файлов' }).getAttribute('aria-expanded'), 'true')
    await page.evaluate(() => window.go(150, 34))
    await row.waitFor()
    await page.evaluate(() => { document.activeElement.blur(); window.go(null, 4) })
    const scroll = page.locator('[data-message-feed]')
    const before = await scroll.evaluate(element => element.scrollTop)
    await page.evaluate(() => window.extend())
    await page.waitForTimeout(200)
    assert.ok(Math.abs((await scroll.evaluate(element => element.scrollTop)) - before) < 20, 'streamed changes preserve position when reading history')
    await page.evaluate(() => window.go(499, 5))
    await page.locator('[data-message-id="m499"]').waitFor()
    await page.evaluate(() => window.go(null, 6))
    await scroll.evaluate(element => { element.scrollTop = element.scrollHeight })
    await page.waitForTimeout(200)
    await page.evaluate(() => window.extend())
    await page.waitForTimeout(300)
    const distance = await scroll.evaluate(element => element.scrollHeight - element.clientHeight - element.scrollTop)
    assert.ok(distance < 180, `stream stays near bottom; distance=${distance}`)
    await page.evaluate(() => window.searchWhileSending())
    await page.locator('[data-message-id="m50"]').waitFor()
    await page.waitForTimeout(200)
    const searchPosition = await scroll.evaluate(element => element.scrollTop)
    await page.evaluate(() => window.extend())
    await page.waitForTimeout(200)
    const streamedPosition = await scroll.evaluate(element => element.scrollTop)
    assert.ok(Math.abs(streamedPosition - searchPosition) < 100, 'a search concurrent with a new user message is not overridden by subsequent streaming')

    await page.evaluate(() => window.go(0, 7))
    const firstRow = page.locator('[data-message-id="m0"]')
    await firstRow.waitFor()
    const firstClass = await firstRow.getAttribute('class')
    assert.ok(firstClass?.includes('pt-6'), 'first message in feed has top padding')
    const secondRow = page.locator('[data-message-id="m1"]')
    if (await secondRow.count() > 0) {
      const secondClass = await secondRow.getAttribute('class')
      assert.ok(!secondClass?.includes('pt-6'), 'subsequent messages do not have extra top padding')
    }
  } finally { await browser.close() }
})
