const { test } = require('node:test')
const assert = require('node:assert/strict')
const { _electron: electron } = require('playwright-core')
const fs = require('node:fs/promises')
const path = require('node:path')
const os = require('node:os')

test('navigation rail opens schedules, plugins and profile settings', { timeout: 45000 }, async () => {
  const root = await fs.mkdtemp(path.join(os.tmpdir(), 'zipply-navigation-'))
  let app
  try {
    app = await electron.launch({ args: ['tests/e2e/bootstrap.cjs'], env: { ...process.env, ZIPPLY_E2E_ROOT: root } })
    const page = await app.firstWindow()
    await page.getByPlaceholder('Напиши что-нибудь…').waitFor()
    const maskedIcon = page.getByRole('button', { name: 'Toggle Sidebar' }).locator('foreignObject div')
    assert.notEqual(await maskedIcon.evaluate(element => getComputedStyle(element).maskImage), 'none', 'shared icons render their SVG mask')
    const frame = page.locator('[data-app-frame]')
    assert.notEqual(await frame.evaluate(element => getComputedStyle(element).borderLeftStyle), 'none')
    assert.notEqual(await page.locator('[data-content-pane]').evaluate(element => getComputedStyle(element).borderLeftStyle), 'none')
    await page.getByRole('button', { name: 'Запланировано', exact: true }).click({ timeout: 3000 })
    await page.locator('#schedule-prompt').waitFor()
    await page.getByRole('button', { name: 'Плагины', exact: true }).click()
    await page.getByRole('heading', { name: 'Плагины', exact: true }).waitFor()
    await page.getByRole('button', { name: 'Профиль', exact: true }).click()
    for (const name of ['Аккаунт', 'Справка', 'Выйти']) assert.equal(await page.getByRole('button', { name, exact: true }).isDisabled(), true)
    await page.keyboard.press('Escape')
    assert.equal(await page.getByRole('group', { name: 'Меню профиля' }).count(), 0)
    await page.getByRole('button', { name: 'Профиль', exact: true }).click()
    await page.getByRole('button', { name: 'Настройки', exact: true }).click()
    await page.getByRole('button', { name: 'Оформление', exact: true }).waitFor()
    await page.getByRole('button', { name: 'Главная', exact: true }).click()
    await page.getByPlaceholder('Напиши что-нибудь…').waitFor()
    const resizer = page.getByTitle('Двойной клик — сброс ширины')
    const before = await resizer.boundingBox()
    await page.mouse.move(before.x + before.width / 2, before.y + 100)
    await page.mouse.down()
    await page.mouse.move(before.x + before.width / 2 + 50, before.y + 100)
    await page.mouse.up()
    const after = await resizer.boundingBox()
    assert.ok(Math.abs(after.x - before.x - 50) < 2)
    await page.getByRole('button', { name: 'Toggle Sidebar' }).click()
    await page.getByRole('button', { name: 'Профиль', exact: true }).click()
    await page.getByRole('button', { name: 'Настройки', exact: true }).click()
    await page.getByRole('button', { name: 'Главная', exact: true }).click()
    await page.getByPlaceholder('Напиши что-нибудь…').waitFor()
  } finally { if (app) await app.close(); await fs.rm(root, { recursive: true, force: true }) }
})
